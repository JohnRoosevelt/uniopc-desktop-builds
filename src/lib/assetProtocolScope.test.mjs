import test from 'node:test'
import assert from 'node:assert/strict'
import { readFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'

const configPath = fileURLToPath(new URL('../../src-tauri/tauri.conf.json', import.meta.url))

test('asset protocol permits state-v8 media generated by the OpenClaw runtime', async () => {
  const config = JSON.parse(await readFile(configPath, 'utf8'))
  const scope = config.app.security.assetProtocol.scope

  assert.ok(scope.includes('$DATA/Uniopc/state-v8/**/media/**'))
  assert.ok(scope.includes('$DATA/Uniopc/state-v8/**/workspace/**'))
  assert.ok(scope.includes('$DATA/uniopc/state-v8/**/media/**'))
  assert.ok(scope.includes('$DATA/uniopc/state-v8/**/workspace/**'))
})
