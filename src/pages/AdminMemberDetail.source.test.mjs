test('plugin rows render the Accio product layer (localized name, inert icon, skills, recommend)', () => {
  const source = read('src/pages/AdminMemberDetail.jsx')

  // Localized display metadata wins over the native manifest strings.
  assert.equal(source.includes('plugin.product?.displayName || plugin.title || plugin.id'), true)
  assert.equal(source.includes('plugin.product?.description || plugin.description || plugin.id'), true)
  // Icon must stay a data-URI <img> so arbitrary plugin SVGs can never execute scripts.
  assert.equal(source.includes('data:image/svg+xml;utf8,${encodeURIComponent(plugin.product.iconSvg)}'), true)
  assert.equal(source.includes('dangerouslySetInnerHTML={{ __html: plugin.product'), false)
  // Bundled SKILL.md packs and recommended prompts surface on the row.
  assert.equal(source.includes('内置技能：'), true)
  assert.equal(source.includes('plugin.product.recommend'), true)
})
