pub const BUNDLED_SYSTEM_PLUGIN_IDS: &[&str] = &[UNIOPC_LOCAL_WORKSPACE_PLUGIN_ID, UNIOPC_DOCUMENTS_PLUGIN_ID, UNIOPC_PRESENTATIONS_PLUGIN_ID];
